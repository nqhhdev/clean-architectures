#!/usr/bin/env python3
"""Checker and map generator for this OKF v0.2 bundle (Python 3 standard library only).

    python3 .okf/tools/okf.py          check, then regenerate map.md
    python3 .okf/tools/okf.py --check  check only (what CI and the pre-commit hook run)
    python3 .okf/tools/okf.py --fix    also rewrite drifted index descriptions and append unlisted files

Enforces the Open Knowledge Format v0.2 conformance rules (every concept has frontmatter with a non-empty
`type`; index.md and log.md follow their reserved structure) plus this bundle's own conventions: the `type`
vocabulary in the root index, a listing index.md in every directory, index entries that match frontmatter,
resolvable relative links and `resource:` paths, and ISO dates in log.md.
"""
import os
import posixpath
import re
import sys

BUNDLE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STACK = os.path.dirname(BUNDLE)  # `resource:` paths are relative to the stack root
RESERVED = {"index.md", "log.md"}
STATUSES = {"draft", "stable", "deprecated"}
ENTRY = re.compile(r"^\* \[(?P<title>.+?)\]\((?P<href>[^)]+)\) - (?P<desc>.*)$")
LINK = re.compile(r"(?<!!)\[[^\]]*\]\(([^)\s]+)\)")


def read(rel):
    with open(os.path.join(BUNDLE, rel), encoding="utf-8") as f:
        return f.read()


def write(rel, text):
    with open(os.path.join(BUNDLE, rel), "w", encoding="utf-8") as f:
        f.write(text)


def unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    return v


def split_frontmatter(text):
    """Return (dict | None, body). Handles the flat `key: value` subset this bundle uses."""
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---\n", 4)
    if end < 0:
        end = text.find("\n---", 4)
        if end < 0 or not text[end:].strip() == "---":
            return None, text
    block = text[4:end]
    body = text[end + 5:]
    data = {}
    for line in block.splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            data[m.group(1)] = unquote(m.group(2))
    return data, body


def outside_fences(text):
    out, fenced = [], False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if not fenced:
            out.append(re.sub(r"`[^`]*`", "", line))
    return "\n".join(out)


def all_md():
    found = []
    for dirpath, dirnames, filenames in os.walk(BUNDLE):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            if name.endswith(".md"):
                found.append(posixpath.relpath(os.path.join(dirpath, name).replace(os.sep, "/"),
                                               BUNDLE.replace(os.sep, "/")))
    return found


def vocabulary(root_index):
    types, active = set(), False
    for line in root_index.splitlines():
        if line.startswith("# "):
            active = line.strip() == "# Concept types"
        elif active:
            types.update(re.findall(r"`([^`]+)`", line.split(" - ")[0]))
    return types


def write_map(meta):
    rows = []
    for f in sorted(meta):
        if f == "map.md":
            continue
        d = meta[f]
        rows.append("| [%s](%s) | %s | %s | %s |" % (
            f, f, d.get("type", "-"), d.get("description", "").replace("|", "\\|"), d.get("tags", "")))
    out = ["---", "type: Reference", 'title: "Bundle Map"',
           'description: "Generated - every file in this bundle with its type, description and tags, for one-read search."',
           "tags: [generated, search]", "status: stable", "---", "",
           "# Bundle Map", "", "> Generated by `python3 .okf/tools/okf.py`. Never edit by hand.", "",
           "| File | Type | Description | Tags |", "|---|---|---|---|"] + rows
    write("map.md", "\n".join(out) + "\n")


def main():
    fix = "--fix" in sys.argv
    check_only = "--check" in sys.argv
    errors = []
    if not os.path.exists(os.path.join(BUNDLE, "map.md")) and not check_only:
        write_map({})  # placeholder so the index can list it; regenerated below
    files = all_md()
    meta = {}

    if "index.md" not in files:
        print("index.md: missing root index")
        return 1
    root_fm, _ = split_frontmatter(read("index.md"))
    if not root_fm or "okf_version" not in root_fm:
        errors.append("index.md: the root index must carry `okf_version` in frontmatter")
    vocab = vocabulary(read("index.md"))
    if not vocab:
        errors.append("index.md: no '# Concept types' section listing the type vocabulary")

    for f in files:
        base = posixpath.basename(f)
        text = read(f)
        fm, body = split_frontmatter(text)
        if base == "index.md":
            keys = set(fm or {}) - ({"okf_version"} if f == "index.md" else set())
            if fm is not None and keys:
                errors.append(f"{f}: index.md must not have frontmatter (only the root may carry okf_version)")
            continue
        if base == "log.md":
            if fm is not None:
                errors.append(f"{f}: log.md must not have frontmatter")
            for line in text.splitlines():
                if line.startswith("## ") and not re.fullmatch(r"## \d{4}-\d{2}-\d{2}.*", line):
                    errors.append(f"{f}: log heading must start with an ISO date: {line!r}")
            continue
        if fm is None:
            errors.append(f"{f}: no frontmatter block")
            continue
        meta[f] = fm
        if not fm.get("type"):
            errors.append(f"{f}: frontmatter has no non-empty 'type'")
        elif vocab and fm["type"] not in vocab:
            errors.append(f"{f}: type '{fm['type']}' is not in the vocabulary in index.md")
        for key in ("title", "description"):
            if not fm.get(key):
                errors.append(f"{f}: missing '{key}'")
        if fm.get("status") and fm["status"] not in STATUSES:
            errors.append(f"{f}: status '{fm['status']}' is not one of {sorted(STATUSES)}")
        res = fm.get("resource")
        if res and not re.match(r"^[a-z]+://", res) and not os.path.exists(os.path.join(STACK, res)):
            errors.append(f"{f}: resource '{res}' does not exist (relative to the stack root)")
        for href in ([] if f == "map.md" else LINK.findall(outside_fences(body))):  # map.md is regenerated below
            if re.match(r"^(https?:|mailto:|#)", href):
                continue
            target = href.split("#")[0]
            if not target:
                continue
            resolved = os.path.normpath(os.path.join(BUNDLE, posixpath.dirname(f), target))
            if not os.path.exists(resolved):
                errors.append(f"{f}: broken link {href}")

    # index.md in every directory that has concepts or subdirectories; entries match frontmatter
    dirs = {posixpath.dirname(f) for f in files}
    for d in sorted(dirs | {""}):
        index = posixpath.join(d, "index.md")
        concepts = sorted(f for f in files
                          if posixpath.dirname(f) == d and posixpath.basename(f) not in RESERVED)
        subdirs = sorted({s.split("/")[len(d.split("/")) if d else 0] for s in dirs
                          if s != d and (s.startswith(d + "/") if d else s != "")})
        if not concepts and not subdirs:
            continue
        if index not in files:
            errors.append(f"{index}: missing (directory has {len(concepts)} concepts, {len(subdirs)} subdirectories)")
            continue
        text = read(index)
        listed = {}
        for line in text.splitlines():
            m = ENTRY.match(line)
            if m:
                listed[m.group("href")] = m
        want = {posixpath.relpath(c, d) if d else c: c for c in concepts}
        want.update({s + "/": None for s in subdirs})
        append = []
        for href, source in want.items():
            if href not in listed:
                errors.append(f"{index}: does not list {href}")
                if source and source in meta:
                    append.append(f"* [{meta[source].get('title', href)}]({href}) - {meta[source].get('description', '')}")
                continue
            entry = listed[href]
            if source and source in meta:
                real = meta[source].get("description", "")
                if entry.group("desc") != real:
                    errors.append(f"{index}: description of {href} differs from its frontmatter")
                    if fix:
                        text = text.replace(entry.group(0), f"* [{entry.group('title')}]({href}) - {real}")
            elif not source and not entry.group("desc").strip():
                errors.append(f"{index}: empty description for {href}")
        for href in listed:
            if href not in want and not os.path.exists(os.path.join(BUNDLE, posixpath.dirname(index), href)):
                errors.append(f"{index}: lists {href} which does not exist")
        if fix and append:
            if "# Concepts" not in text:
                text = text.rstrip() + "\n\n# Concepts\n"
            text = text.rstrip() + "\n" + "\n".join(append) + "\n"
        if fix:
            write(index, text)

    if errors:
        print("\n".join(sorted(set(errors))))
        print(f"\n{len(set(errors))} problem(s)")
        return 1

    if not check_only:
        write_map(meta)
    print(f"ok: {len(meta)} concepts, {len(files)} markdown files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
