import 'package:clean_architecture/domain/errors/email_errors.dart';
import 'package:clean_architecture/domain/models/email.dart';
import 'package:clean_architecture/utils/result.dart';
import 'package:flutter_test/flutter_test.dart';

Result<Email> create({String id = '1', String subject = 'Hi'}) => Email.create(
  id: id,
  subject: subject,
  sender: ' a@example.com ',
  preview: 'p',
  receivedAt: DateTime(2026, 1, 1, 12),
  isRead: false,
);

Email ok(Result<Email> r) => (r as Success<Email>).value;

void main() {
  test('create trims text and stores receivedAt as UTC', () {
    final email = ok(create(subject: '  Hello '));
    expect(email.subject, 'Hello');
    expect(email.sender, 'a@example.com');
    expect(email.receivedAt.isUtc, isTrue);
  });

  test('a blank subject stays empty; the UI decides what to show', () {
    expect(ok(create(subject: '  ')).subject, isEmpty);
  });

  test('create rejects a blank id with a coded error', () {
    final error = (create(id: ' ') as Failure<Email>).error;
    expect(error, EmailErrors.invalidId);
    expect(error.code, 'Emails.InvalidId');
  });

  group('generated by freezed', () {
    test('value equality and hashCode', () {
      expect(ok(create()), ok(create()));
      expect(ok(create()).hashCode, ok(create()).hashCode);
      expect(ok(create()), isNot(ok(create(subject: 'Other'))));
    });

    test('copyWith changes only the given field', () {
      final email = ok(create());
      final read = email.copyWith(isRead: true);
      expect(read.isRead, isTrue);
      expect(read.id, email.id);
      expect(email.isRead, isFalse, reason: 'the original is unchanged');
    });
  });
}
